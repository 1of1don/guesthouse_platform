// TYPES & DATA MODELS FOR MICASA SUCASA ADMIN PORTAL

// This file defines the shape (blueprints) of our data objects in TypeScript.
// If you want to add a new property to a Guesthouse or an Admin user, you
// update it here first so TypeScript helps prevent typos across the app!


// Blueprint for a Guesthouse property in our system
export interface Guesthouse {
  _id?: string;               // Unique database ID generated by Firebase or LocalStorage
  name: string;               // Name of the guesthouse (e.g., "MiCasa SuCasa Guesthouse")
  city: string;               // City or town (e.g., "Gaborone", "Kasane", "Maun")
  country: string;            // Country name (default is "Botswana")
  description: string;        // Brief story and summary of the guesthouse
  amenities: string[];        // Array of amenities (e.g., ["Free Wi-Fi", "Swimming Pool"])
  contactDetails: string;     // Phone number or email for booking inquiries
  coordinates: {              // Latitude and Longitude for Google Maps pins
    lat: number;
    lng: number;
  };
  pricePerNight: number;      // Price per night in BWP (Pula) or chosen currency
  rating?: number;            // Average rating, read from averageRating (written by the mobile app)
  ratingCount?: number;       // How many customers have rated it
  logo?: string;              // Firebase Storage download URL for the main photo
  gallery?: string[];         // Firebase Storage download URLs for gallery photos
  createdAt?: string;         // ISO date string of when this listing was created
  isSuspended?: boolean;      // true = hidden from the mobile app. Missing means active.
  status?: 'active' | 'suspended'; // Same as isSuspended, kept for older records
}

// Blueprint for a customer who signed up on the mobile app
export interface Customer {
  _id: string;                // Firebase Auth uid
  name: string;
  email: string;
  createdAt?: string;
  isSuspended?: boolean;      // true = can still browse but can't post reviews
}

// A rating + comment a customer left on a guesthouse (ratings collection)
export interface Review {
  _id: string;                // `${guesthouseId}_${customerId}`
  guesthouseId: string;
  customerId: string;
  customerName: string;
  score: number;              // 1 to 5
  comment: string;
  createdAt?: string;
  isHidden: boolean;          // hidden by an admin, not counted in the average
}

// Possible administrator roles
// 'Owner' = full system rights, 'Admin' = can add, edit, and delete guesthouses
export type AdminRole = 'Owner' | 'Admin';

// Blueprint for an Administrator account
export interface AdminUser {
  _id: string;                // Unique ID for the admin record
  name: string;               // Full name of admin (e.g., "Ontiretse Bagwasi")
  email: string;              // Admin login email (e.g., "onty@micasa.com")
  role: AdminRole;            // 'Owner' or 'Admin'
  status?: 'Active' | 'Invited'; // Account status
  createdAt?: string;         // Date account was added
}

// Helper blueprint for city breakdown on the Dashboard
export interface CityPriceStat {
  city: string;               // Name of the city (e.g., "Gaborone")
  count: number;              // How many guesthouses are in this city
  avgPrice: number;           // Average nightly price in this city
}

// Blueprint for Dashboard summary numbers (KPIs)
export interface DashboardStats {
  totalGuesthouses: number;   // Total count of all registered guesthouses
  suspendedCount: number;     // How many of those are hidden from the mobile app
  topCity: {                  // City with the highest number of listings
    name: string;
    count: number;
  };
  highestRated: {             // Top rated guesthouse (synced from mobile)
    name: string;
    rating: number;
  };
  addedThisMonth: number;     // How many listings were registered this month
  averagePrice: number;       // Average price across all guesthouses
  cityDistribution: CityPriceStat[]; // List of cities with count and avg price
  recent: Guesthouse[];       // List of guesthouses to show on the dashboard table
}
